    /** Liest die Client-Sprache des ersten Spielers (jede Sekunde aufrufen). */
    static void update(MinecraftServer server) {
        for (ServerPlayer p : server.getPlayerList().getPlayers()) {
            String l = p.clientInformation().language();
            if (l == null || l.isEmpty()) return;
            english = !l.toLowerCase(Locale.ROOT).startsWith("de");
            return;
        }
    }

    /** Uebersetzt einen (zusammengesetzten) deutschen Text, wenn die Sprache nicht deutsch ist. */
    static String tr(String s) {
        if (!english || s == null || s.isEmpty()) return s;
        String ex = EXACT.get(s);
        if (ex != null) return ex;
        String r = s;
        for (String[] e : FRAG) if (r.contains(e[0])) r = r.replace(e[0], e[1]);
        return r;
    }

    /** Ersatz fuer Component.literal: uebersetzt automatisch. */
    static MutableComponent lit(String s) { return Component.literal(tr(s)); }
